function result=gg_export_run(data,id,split,out,selection, ...
    oof_rule,oof_lr,cfg,folder,base)
alpha=selection.alpha;
final=(1-alpha)*out.rule_score+alpha*out.lr_score;
vi=split.val_idx;ti=split.test_idx;tr=split.train_idx;
[yv,pv]=gg_group_scores(data.y,final(vi),vi,id);
[yt,pt,tg]=gg_group_scores(data.y,final(ti),ti,id);
[threshold,~]=select_threshold(yv,pv,cfg.threshold_metric);
vm=binary_metrics(yv,pv,threshold);gm=binary_metrics(yt,pt,threshold);
em=binary_metrics(data.y(ti),final(ti),threshold);
hp=select_high_precision_threshold(yv,pv,cfg.high_precision_target, ...
    cfg.high_precision_min_calls);
oof_final=(1-alpha)*oof_rule(tr)+alpha*oof_lr(tr);
[yo,po]=gg_group_scores(data.y,oof_final,tr,id);
om=binary_metrics(yo,po,0.5);
% OOF labels select alpha: these training summaries are not independent tests.
T=id.record_table(ti,:);T.RuleProbability=out.rule_score(ti);
T.LRProbability=out.lr_score(ti);T.FinalProbability=final(ti);
T.Prediction=final(ti)>=threshold;
writetable(T,fullfile(folder,'test_predictions.csv'));
G=table(tg,yt,pt,pt>=threshold,'VariableNames', ...
    {'GroupID','Label','FinalProbability','Prediction'});
writetable(G,fullfile(folder,'test_group_predictions.csv'));
V=id.record_table(vi,:);V.RuleProbability=out.rule_score(vi);
V.LRProbability=out.lr_score(vi);V.FinalProbability=final(vi);
writetable(V,fullfile(folder,'validation_predictions.csv'));
rows=struct([]);
names={'RULE','LR37','GC_BRB'};scores={out.rule_score,out.lr_score,final};
for j=1:numel(names)
    [a,b]=gg_group_scores(data.y,scores{j}(vi),vi,id);
    [c,d]=gg_group_scores(data.y,scores{j}(ti),ti,id);
    [th,~]=select_threshold(a,b,cfg.threshold_metric);
    v=binary_metrics(a,b,th);g=binary_metrics(c,d,th);
    e=binary_metrics(data.y(ti),scores{j}(ti),th);
    row=struct('Model',string(names{j}),'GroupValAUPRC',v.AUPRC, ...
        'GroupTestAUPRC',g.AUPRC,'GroupTestAUROC',g.AUROC, ...
        'EntryTestAUPRC',e.AUPRC,'EntryTestAUROC',e.AUROC, ...
        'GroupValidationMCCThreshold',th);
    rows=append_struct(rows,row);
end
writetable(struct2table(rows),fullfile(folder,'branch_comparison.csv'));
summary=struct('Target',string(split.target),'Run',split.run,'Seed',split.seed, ...
    'IdentityProtocol',string(cfg.protocol_version),'Stage',string(cfg.stage), ...
    'TrainRecords',numel(tr),'ValidationRecords',numel(vi), ...
    'TestRecords',numel(ti),'TestGroups',numel(tg), ...
    'ExcludedLabelledAliases',numel(split.excluded_idx), ...
    'FusionAlphaLRWeight',alpha,'SelectedOmicsLambda',out.evidence.omics_selected_lambda, ...
    'SelectedLRLambda',out.lr.selected_lambda,'GroupTrainSelectedOOFAUPRC',om.AUPRC, ...
    'GroupValAUPRC',vm.AUPRC,'GroupTestAUPRC',gm.AUPRC, ...
    'GroupTestAUROC',gm.AUROC,'GroupTestMCC',gm.MCC, ...
    'GroupTestF1',gm.F1,'GroupTestBrier',gm.Brier, ...
    'TestAUPRC',em.AUPRC,'TestAUROC',em.AUROC, ...
    'ValidationMCCThreshold',threshold,'HPThresholdValid',hp.Valid, ...
    'HPThreshold',hp.Threshold,'HPValidationPrecision',hp.Precision, ...
    'HPValidationCalls',hp.PredictedPositive);
% Candidate labels are never imputed: groups with ANY known label are excluded.
ui=find(~isfinite(data.y));candidate=id.record_table(ui,:);
candidate.EligibleUnlabelledGroup=~isfinite(id.group_label(id.group_id(ui)));
candidate.RuleProbability=out.rule_score(ui);candidate.LRProbability=out.lr_score(ui);
candidate.FinalProbability=final(ui);
writetable(candidate,fullfile(folder,'candidate_entry_scores.csv'));
eligible=ui(~isfinite(id.group_label(id.group_id(ui))));
[groups,~,g]=unique(id.group_id(eligible));
pp=accumarray(g,final(eligible),[],@mean);
calls=hp.Valid & pp>=hp.Threshold;
C=table(groups,pp,calls,'VariableNames', ...
    {'GroupID','MeanFinalProbability','AboveValidationHPThreshold'});
writetable(C,fullfile(folder,'candidate_group_scores.csv'));
if cfg.export_baseline_features
    ix=[tr;vi;ti];partition=[repmat("Train",numel(tr),1); ...
        repmat("Validation",numel(vi),1);repmat("Test",numel(ti),1)];
    features=out.evidence.feature_matrix(ix,:);
    if size(features,2)~=37,error('GG:Features','Expected 37 columns.');end
    feature_columns=cellstr(compose('F%02d',1:37));
    B=table(ix,id.group_id(ix),double(data.y(ix)),partition, ...
        'VariableNames',{'GlobalIndex','GroupID','Label','Partition'});
    B=[B,array2table(features,'VariableNames',feature_columns)];
    feature_file=fullfile(folder,'baseline_features.csv');
    writetable(B,feature_file);
    dictionary=table(string(feature_columns(:)),residual_feature_names(data), ...
        'VariableNames',{'Column','Meaning'});
    writetable(dictionary,fullfile(folder,'feature_dictionary.csv'));
    metadata=struct('Protocol',cfg.protocol_version,'Stage',cfg.stage, ...
        'Target',split.target,'Run',split.run,'Seed',split.seed, ...
        'BaseFingerprint',base,'FeatureSHA256',gg_hash(feature_file,true), ...
        'FeatureColumns',{feature_columns}, ...
        'TuningSubset','Validation only; complete outer OOF is used for GC-BRB alpha', ...
        'PrimaryMetricUnit','conservative_identity_group');
    gg_jsonwrite(fullfile(folder,'baseline_metadata.json'),metadata);
end
gg_jsonwrite(fullfile(folder,'run_status.json'), ...
    struct('Protocol',cfg.protocol_version,'Stage',cfg.stage, ...
    'Target',split.target,'Run',split.run,'Completed',true, ...
    'FormalOptimizationSettings',~strcmp(cfg.stage,'smoke'), ...
    'BaseFingerprint',base,'CompleteOuterOOF',true, ...
    'HeldoutLabelIsolation',true,'GroupValAUPRC',vm.AUPRC, ...
    'GroupTestAUPRC',gm.AUPRC,'EntryTestAUPRC',em.AUPRC));
result=struct('summary',summary,'selection',selection, ...
    'base_fingerprint',base,'split',split,'threshold',threshold, ...
    'high_precision',hp,'group_test_metrics',gm,'entry_test_metrics',em);
end
